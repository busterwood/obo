#!/usr/bin/env python3
"""Build the obo command-line tools by concatenation.

    python3 obo/tools/build_tools.py [TOOL ...] [--out DIR] [--obo PATH] [--rt DIR]

There are no modules yet, so a tool is built by concatenating, in this fixed
order: a generated header (relative source paths, no timestamp, so the generated
source is reproducible), lib/str.obo, lib/io.obo, and the tool source. The rule
is that a prelude may use only earlier preludes, and within a file a declaration
may use only earlier declarations (obo requires declare-before-use).

The default tools are cat, wc and sort. Paths resolve to absolute paths, so the
builder's behavior does not depend on the caller's cwd: ROOT is the directory
holding this script's tools/ (that is, obo/); --obo defaults to $OBO or
ROOT/obo, --rt to ROOT, --out to ROOT/build/tools. The generated sources and
binaries live only under --out, and every requested tool must compile for the
exit status to be 0.

Stage 2: the builder creates ROOT/.obo/sym and passes --sym-dir to every compile.
The tools are still single-file roots (prelude concatenation), so no .sym is
written today; the flag is always exercised and a tool that becomes a module root
(with its own `module` header and imports) builds unchanged. Using --deps for
make prerequisites is deferred until a tool is a module; see FORK.md.

There is no cache and no --force: rebuilding three tools is cheap, and a cache
would add staleness bugs. A compile failure maps the generated file's line
numbers back to the source file and line and exits 2 with the compiler's
message. The phase-2 probe compiles (does not run) a tiny well-typed program
that names every incremental-I/O builtin; a failure means phase 2 (openFile,
readFd, writeFd, closeFile, stdin, stdout, stderr and lib/io.obo) is missing.

tests/tools.py imports build() to make its private temporary build, so the
concatenation rule lives in exactly one place.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # .../obo
TOOLS = ('cat', 'wc', 'sort')
SYMDIR = os.path.join(ROOT, '.obo', 'sym')

HEADER = (
    '// Generated by tools/build_tools.py from {sources}.\n'
    '// Do not edit; run `make tools` (or `python3 tools/build_tools.py`) to rebuild.\n'
    '// Preludes are concatenated in the fixed order str, io, tool (declare-before-use).\n'
)

PROBE = '''// phase-2 builtin probe: compile only, never run
fn main() {
    let out = stdout()
    let err = stderr()
    let inp = stdin()
    let data = new []byte(1)
    data[0] = 'x'
    let wr = writeFd(out, data)
    match wr {
        ok { }
        err { }
    }
    let rd = readFd(inp, 1)
    match rd {
        ok { }
        err { }
    }
    let o = openFile("probe", "r")
    match o {
        ok {
            let fd = o.value
            let c = closeFile(fd)
            match c {
                ok { }
                err { }
            }
        }
        err { }
    }
    println(err)
}
'''


class BuildError(Exception):
    """A setup or compile failure; the caller reports it and exits 2."""


def _read(path):
    try:
        with open(path, 'r', encoding='utf-8', newline='') as f:
            return f.read()
    except OSError as e:
        raise BuildError(f"cannot read {path}: {e.strerror}")


def _compile(obo, src, out, rt):
    os.makedirs(SYMDIR, exist_ok=True)
    p = subprocess.run([obo, src, '-o', out, '--rt', rt, '--sym-dir', SYMDIR],
                       capture_output=True, text=True)
    return p.returncode, p.stdout, p.stderr


def _map_error(stderr, gen, segments):
    """Rewrite `<generated>:LINE:COL:` to `<source>:LINE:COL:`, where segments is
    a list of (generated_start_line, source_label) in concatenation order."""
    prefix = re.escape(gen) + r':(\d+):(\d+):'
    out = []
    for line in stderr.splitlines():
        m = re.match(prefix, line)
        if not m:
            out.append(line)
            continue
        gl = int(m.group(1))
        best = None
        for start, label in segments:
            if gl >= start:
                best = (start, label)
        if best is None:
            out.append(line)
            continue
        start, label = best
        out.append(f"{label}:{gl - start + 1}:{m.group(2)}:" + line[m.end():])
    return '\n'.join(out) + ('\n' if out else '')


def _concatenate(tool):
    """Return (text, segments): the generated source and the line map."""
    sources = [('lib/str.obo', os.path.join(ROOT, 'lib', 'str.obo')),
               ('lib/io.obo', os.path.join(ROOT, 'lib', 'io.obo')),
               (f'programs/{tool}.obx', os.path.join(ROOT, 'programs', tool + '.obx'))]
    header = HEADER.format(sources=', '.join(label for label, _ in sources))
    parts = [header]
    lines = header.count('\n')
    segments = []
    for label, path in sources:
        text = _read(path)
        if not text.endswith('\n'):
            text += '\n'
        segments.append((lines + 1, label))
        parts.append(text)
        lines += text.count('\n')
    return ''.join(parts), segments


def probe(obo, rt, out):
    """Compile the well-typed phase-2 builtin probe; BuildError if it fails."""
    os.makedirs(out, exist_ok=True)
    src = os.path.join(out, '.phase2_probe.obo')
    exe = os.path.join(out, '.phase2_probe')
    with open(src, 'w', encoding='utf-8', newline='') as f:
        f.write(PROBE)
    try:
        rc, _, err = _compile(obo, src, exe, rt)
    finally:
        for p in (src, exe):
            try:
                os.unlink(p)
            except OSError:
                pass
    if rc != 0:
        first = err.strip().splitlines()[0] if err.strip() else f"exit {rc}"
        raise BuildError(
            "phase 2 (incremental I/O) is a prerequisite: the builtin probe failed "
            f"to compile: {first}")


def build(names, out, obo, rt):
    """Build the named tools into out; return their absolute paths.

    Raises BuildError for a missing compiler/runtime/source or a compile failure."""
    if not names:
        raise BuildError("no tools requested")
    for name in names:
        if name not in TOOLS:
            raise BuildError(f"unknown tool '{name}' (choose from {', '.join(TOOLS)})")
    for name in names:
        _read(os.path.join(ROOT, 'lib', 'str.obo'))
        _read(os.path.join(ROOT, 'programs', name + '.obx'))
        io_path = os.path.join(ROOT, 'lib', 'io.obo')
        if not os.path.isfile(io_path):
            raise BuildError(
                "phase 2 (incremental I/O) is a prerequisite: lib/io.obo is missing")
    if not os.path.isfile(obo) or not os.access(obo, os.X_OK):
        raise BuildError(f"compiler not found or not executable: {obo}")
    for f in ('runtime_text.bin', 'runtime_data.bin'):
        if not os.path.isfile(os.path.join(rt, f)):
            raise BuildError(f"runtime file missing: {os.path.join(rt, f)}")

    os.makedirs(out, exist_ok=True)
    probe(obo, rt, out)

    built = []
    for name in names:
        text, segments = _concatenate(name)
        gen = os.path.join(out, name + '.obo')
        exe = os.path.join(out, name)
        with open(gen, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        rc, _, err = _compile(obo, gen, exe, rt)
        if rc != 0:
            mapped = _map_error(err, gen, segments)
            if not mapped.strip():
                mapped = f"compiler exited {rc} with no message"
            raise BuildError(f"{name}: compile failed\n{mapped.rstrip()}")
        built.append(exe)
    return built


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('tools', nargs='*', default=list(TOOLS),
                    help=f"tools to build (default: {' '.join(TOOLS)})")
    ap.add_argument('--out', default=os.path.join(ROOT, 'build', 'tools'))
    ap.add_argument('--obo', default=os.environ.get('OBO') or os.path.join(ROOT, 'obo'))
    ap.add_argument('--rt', default=ROOT)
    a = ap.parse_args(argv)
    names = a.tools or list(TOOLS)
    try:
        built = build(names, os.path.abspath(a.out), os.path.abspath(a.obo),
                      os.path.abspath(a.rt))
    except BuildError as e:
        print(f"build_tools.py: {e}", file=sys.stderr)
        return 2
    for exe in built:
        print(f"built {exe}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
