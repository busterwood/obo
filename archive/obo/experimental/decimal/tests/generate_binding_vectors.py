#!/usr/bin/env python3
"""Generate C fixtures for private dec24 binding validation."""
from __future__ import annotations

import argparse
import hashlib
import json
import os

import binding_oracle as o


def c_u64(v: int) -> str:
    return f"0x{v:016x}ULL"


def write_header(cases: dict, path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by generate_binding_vectors.py; private D1 fixture */\n")
        f.write("#ifndef DEC_BIND_VECTORS_GENERATED_H\n")
        f.write("#define DEC_BIND_VECTORS_GENERATED_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("typedef struct { int sign; uint64_t lo, hi; int exp; "
                "unsigned dscale; long long p; long long s; int exact_status; "
                "unsigned mode; int round_status; int rsign; uint64_t rlo, rhi; "
                "int rexp; unsigned rdscale; } DecBindVec;\n\n")
        f.write("static const DecBindVec dec_bind_vectors[] = {\n")
        for c in cases["cases"]:
            r = c["round"]
            f.write(
                f"  {{{c['sign']},{c_u64(c['coeff'] & ((1 << 64) - 1))},"
                f"{c_u64(c['coeff'] >> 64)},{c['exp']},{c['dscale']},"
                f"{c['p']}LL,{c['s']}LL,{c['exact_status']},{c['mode']},"
                f"{r['status']},{r['sign']},"
                f"{c_u64(r['coeff'] & ((1 << 64) - 1))},"
                f"{c_u64(r['coeff'] >> 64)},{r['exp']},{r['dscale']}}},\n")
        f.write("};\n")
        f.write(f"#define DEC_BIND_VECTORS_COUNT {len(cases['cases'])}u\n\n")
        f.write("#endif\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    cases = o.build_binding_cases()
    path = os.path.join(out, "binding_vectors_generated.h")
    write_header(cases, path)
    result = {
        "format": "obo-decimal-binding-fixtures-v1",
        "counts": cases["counts"],
        "header": os.path.basename(path),
        "header_sha256": hashlib.sha256(open(path, "rb").read()).hexdigest(),
        "oracle": "binding_oracle.py",
        "oracle_sha256": hashlib.sha256(
            open(os.path.join(os.path.dirname(__file__),
                              "binding_oracle.py"), "rb").read()).hexdigest(),
    }
    with open(os.path.join(out, "binding_generator_results.json"), "w",
              encoding="utf-8") as f:
        json.dump(result, f, indent=2, sort_keys=True)
        f.write("\n")
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
