#!/usr/bin/env python3
"""Generate C fixtures for the private dec24 text protocol.

The expected values come from decimal_text_oracle.py.  Text is emitted as
escaped C string bytes so embedded NUL and UTF-8 cases exercise the explicit
length API rather than a C string terminator.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

import decimal_text_oracle as o


def c_bytes_literal(text: str) -> tuple[str, int]:
    data = text.encode("utf-8")
    out = ['"']
    for b in data:
        if 32 <= b < 127 and b not in (34, 92):
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    out.append('"')
    return "".join(out), len(data)


def c_u64(v: int) -> str:
    return f"0x{v:016x}ULL"


def write_header(cases: dict, path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by generate_text_vectors.py; private D1 fixture */\n")
        f.write("#ifndef DEC_TEXT_VECTORS_GENERATED_H\n")
        f.write("#define DEC_TEXT_VECTORS_GENERATED_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("typedef struct { const char *text; unsigned len; int status; "
                "int sign; uint64_t lo, hi; int exp; unsigned dscale; "
                "const char *canonical; const char *display; "
                "int display_status; } DecTextVec;\n")
        f.write("typedef struct { int sign; uint64_t lo, hi; int exp; "
                "unsigned dscale; const char *canonical; int display_status; "
                "const char *display; } DecFormatVec;\n\n")
        f.write("static const DecTextVec dec_text_vectors[] = {\n")
        for c in cases["cases"]:
            text, n = c_bytes_literal(c["text"])
            r = c
            canon, _ = c_bytes_literal(r.get("canonical", ""))
            disp, _ = c_bytes_literal(r.get("display", ""))
            f.write(
                f"  {{{text},{n}u,{r['status']},{r['sign']},"
                f"{c_u64(r['coeff'] & ((1 << 64) - 1))},"
                f"{c_u64(r['coeff'] >> 64)},{r['exp']},{r['dscale']},"
                f"{canon},{disp},{r.get('display_status', o.OK)}}},\n")
        f.write("};\n")
        f.write(f"#define DEC_TEXT_VECTORS_COUNT {len(cases['cases'])}u\n\n")

        f.write("static const DecFormatVec dec_format_vectors[] = {\n")
        only = []
        for sign, coeff, exp, dscale in o.FORMAT_ONLY:
            canon = o.canonical_text(sign, coeff, exp, dscale)
            st, disp = o.display_text(sign, coeff, exp, dscale)
            # Huge fixed displays are size-query cases in the C harness, not
            # header strings.
            if len(disp) > 4096:
                continue
            only.append((sign, coeff, exp, dscale, canon, st, disp))
        for sign, coeff, exp, dscale, canon, st, disp in only:
            cs, _ = c_bytes_literal(canon)
            ds, _ = c_bytes_literal(disp)
            f.write(f"  {{{sign},{c_u64(coeff & ((1 << 64) - 1))},"
                    f"{c_u64(coeff >> 64)},{exp},{dscale},{cs},{st},{ds}}},\n")
        f.write("};\n")
        f.write(f"#define DEC_FORMAT_VECTORS_COUNT {len(only)}u\n\n")
        f.write("#endif\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    cases = o.build_text_cases()
    path = os.path.join(out, "text_vectors_generated.h")
    write_header(cases, path)
    result = {
        "format": "obo-decimal-text-fixtures-v1",
        "seed": cases["seed"],
        "counts": cases["counts"],
        "header": os.path.basename(path),
        "header_sha256": hashlib.sha256(open(path, "rb").read()).hexdigest(),
        "oracle": "decimal_text_oracle.py",
        "oracle_sha256": hashlib.sha256(
            open(os.path.join(os.path.dirname(__file__),
                              "decimal_text_oracle.py"), "rb").read()).hexdigest(),
    }
    with open(os.path.join(out, "text_generator_results.json"), "w",
              encoding="utf-8") as f:
        json.dump(result, f, indent=2, sort_keys=True)
        f.write("\n")
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
