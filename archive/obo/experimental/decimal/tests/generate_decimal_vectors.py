#!/usr/bin/env python3
"""Generate decimal cases.json and the C test's vectors_generated.h.

The Python integer model in decimal_oracle.py is the expected-value source.
The C prototype is checked against these vectors; Python decimal is a
secondary cross-check under explicit contexts only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

import decimal_oracle as d

HERE = os.path.dirname(os.path.abspath(__file__))


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def parts(a: d.Dec) -> tuple[int, int, int, int, int]:
    return (a.sign, a.coeff & ((1 << 64) - 1), a.coeff >> 64,
            a.exp, a.dscale)


def c_u64(v: int) -> str:
    return f"0x{v:016x}ULL"


def write_header(v: dict, path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by generate_decimal_vectors.py; private prototype */\n")
        f.write("#ifndef DEC24_VECTORS_GENERATED_H\n#define DEC24_VECTORS_GENERATED_H\n")
        f.write("#include <stdint.h>\n\n")
        f.write("typedef struct { int sign_a; uint64_t alo, ahi; int ea; unsigned da; "
                "int sign_b; uint64_t blo, bhi; int eb; unsigned db; "
                "unsigned mode; int status; int sign_r; uint64_t rlo, rhi; int er; unsigned dr; } DecOpVec;\n")
        f.write("typedef struct { int sign_a; uint64_t alo, ahi; int ea; unsigned da; "
                "unsigned target; unsigned mode; int status; int sign_r; uint64_t rlo, rhi; "
                "int er; unsigned dr; } DecQuantVec;\n")
        f.write("typedef struct { uint64_t a,b,lo,hi; } Mul64Vec;\n")
        f.write("typedef struct { uint64_t alo,ahi,blo,bhi,w0,w1,w2,w3; } Mul128Vec;\n")
        f.write("typedef struct { uint64_t n0,n1,n2,n3,d,q0,q1,q2,q3,rem; } Div256Vec;\n")
        f.write("typedef struct { uint64_t n0,n1,n2,n3,dlo,dhi,q0,q1,q2,q3,r0,r1,r2,r3; } Div256x128Vec;\n")
        f.write("typedef struct { int sign_a; uint64_t alo, ahi; int ea; unsigned da; "
                "int sign_b; uint64_t blo, bhi; int eb; unsigned db; int order; } DecCmpVec;\n\n")

        def emit_op(name: str, arr: list) -> None:
            f.write(f"static const DecOpVec {name}[] = {{\n")
            for v in arr:
                a = d.Dec(**v["a"])
                b = d.Dec(**v["b"])
                r = d.Dec(**v["r"]) if v["status"] == d.OK else d.zero()
                sa, alo, ahi, ea, da = parts(a)
                sb, blo, bhi, eb, db = parts(b)
                sr, rlo, rhi, er, dr = parts(r)
                f.write(f"  {{{sa},{c_u64(alo)},{c_u64(ahi)},{ea},{da},"
                        f"{sb},{c_u64(blo)},{c_u64(bhi)},{eb},{db},"
                        f"{v['mode']},{v['status']},{sr},{c_u64(rlo)},{c_u64(rhi)},{er},{dr}}},\n")
            f.write("};\n")
            f.write(f"#define {name.upper()}_COUNT {len(arr)}u\n\n")

        emit_op("dec_add_vectors", v["add"])
        emit_op("dec_sub_vectors", v["sub"])
        emit_op("dec_mul_vectors", v["mul"])

        f.write("static const DecQuantVec dec_quantize_vectors[] = {\n")
        for q in v["quantize"]:
            a = d.Dec(**q["a"])
            r = d.Dec(**q["r"]) if q["status"] == d.OK else d.zero()
            sa, alo, ahi, ea, da = parts(a)
            sr, rlo, rhi, er, dr = parts(r)
            f.write(f"  {{{sa},{c_u64(alo)},{c_u64(ahi)},{ea},{da},"
                    f"{q['target']},{q['mode']},{q['status']},{sr},"
                    f"{c_u64(rlo)},{c_u64(rhi)},{er},{dr}}},\n")
        f.write("};\n")
        f.write(f"#define DEC_QUANTIZE_VECTORS_COUNT {len(v['quantize'])}u\n\n")

        f.write("static const Mul64Vec dec_mul64_vectors[] = {\n")
        for a, b, lo, hi in v["mul64"]:
            f.write(f"  {{{c_u64(a)},{c_u64(b)},{c_u64(lo)},{c_u64(hi)}}},\n")
        f.write("};\n")
        f.write(f"#define DEC_MUL64_VECTORS_COUNT {len(v['mul64'])}u\n\n")

        f.write("static const Mul128Vec dec_mul128_vectors[] = {\n")
        for row in v["mul128"]:
            f.write("  {" + ",".join(c_u64(x) for x in row) + "},\n")
        f.write("};\n")
        f.write(f"#define DEC_MUL128_VECTORS_COUNT {len(v['mul128'])}u\n\n")

        f.write("static const Div256Vec dec_div256_64_vectors[] = {\n")
        for row in v["div256_64"]:
            f.write("  {" + ",".join(c_u64(x) for x in row) + "},\n")
        f.write("};\n")
        f.write(f"#define DEC_DIV256_64_VECTORS_COUNT {len(v['div256_64'])}u\n\n")

        f.write("static const Div256x128Vec dec_div256_128_vectors[] = {\n")
        for row in v["div256_128"]:
            f.write("  {" + ",".join(c_u64(x) for x in row) + "},\n")
        f.write("};\n")
        f.write(f"#define DEC_DIV256_128_VECTORS_COUNT {len(v['div256_128'])}u\n\n")

        f.write("static const DecCmpVec dec_cmp_vectors[] = {\n")
        for row in v["cmp"]:
            a = d.Dec(**row["a"])
            b = d.Dec(**row["b"])
            sa, alo, ahi, ea, da = parts(a)
            sb, blo, bhi, eb, db = parts(b)
            f.write(f"  {{{sa},{c_u64(alo)},{c_u64(ahi)},{ea},{da},"
                    f"{sb},{c_u64(blo)},{c_u64(bhi)},{eb},{db},{row['order']}}},\n")
        f.write("};\n")
        f.write(f"#define DEC_CMP_VECTORS_COUNT {len(v['cmp'])}u\n\n")
        f.write("#endif\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=HERE,
                    help="directory for generated cases/header/results")
    args = ap.parse_args()
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    v = d.build_vectors()
    cases_path = os.path.join(out, "cases.json")
    with open(cases_path, "w", encoding="utf-8") as f:
        json.dump(v, f, indent=2, sort_keys=True)
        f.write("\n")
    header_path = os.path.join(out, "vectors_generated.h")
    write_header(v, header_path)
    cross = d.crosscheck_decimal_module(v)
    result = {
        "format": "obo-decimal-prototype-artifacts-v1",
        "python": sys.version.split()[0],
        "seed": v["seed"],
        "model": "decimal_oracle.py",
        "model_sha256": sha256(os.path.join(HERE, "decimal_oracle.py")),
        "corpus": "cases.json",
        "corpus_sha256": sha256(cases_path),
        "vectors_header": "vectors_generated.h",
        "vectors_header_sha256": sha256(header_path),
        "counts": v["counts"],
        "python_decimal_crosscheck": {
            "context": "prec=38, explicit rounding mode; UNNECESSARY skipped",
            "checked_ok_cases": cross["checked"],
            "numeric_equal": cross["numeric_equal"],
            "mismatches": len(cross["mismatches"]),
            "mismatch_sample": cross["mismatches"][:5],
            "note": "not a claim that Python decimal defaults or flags match the language",
        },
        "prototype_max_dscale": d.MAX_DSCALE,
        "prototype_nonzero_quantize_max_dscale": d.NONZERO_QUANTIZE_MAX_DSCALE,
        "database": "not used; no database service was run",
    }
    with open(os.path.join(out, "generator_results.json"), "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, sort_keys=True)
        f.write("\n")
    print(json.dumps({"counts": v["counts"],
                      "corpus_sha256": result["corpus_sha256"],
                      "crosscheck": result["python_decimal_crosscheck"]}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
