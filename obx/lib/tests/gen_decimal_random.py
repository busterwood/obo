#!/usr/bin/env python3
"""Generates run/decimal_random.obx: random Decimal operations whose expected
results come from Python's decimal module with exact precision. Rerun after a
change to the rules (the seed is fixed, so the output is stable):

    python3 obx/lib/tests/gen_decimal_random.py
"""
import decimal, os, random
from decimal import Decimal as D

HERE = os.path.dirname(os.path.abspath(__file__))
ctx = decimal.Context(prec=400, Emin=-999999, Emax=999999, traps=[])
MODES = {
    'HALF_EVEN': decimal.ROUND_HALF_EVEN, 'HALF_AWAY': decimal.ROUND_HALF_UP,
    'HALF_TOWARD_ZERO': decimal.ROUND_HALF_DOWN, 'TOWARD_ZERO': decimal.ROUND_DOWN,
    'AWAY': decimal.ROUND_UP, 'FLOOR': decimal.ROUND_FLOOR, 'CEILING': decimal.ROUND_CEILING,
    'UNNECESSARY': None,
}


def rnd_dec(r):
    """A random literal text: coefficient of 1..38 digits, a fraction part."""
    kind = r.random()
    if kind < 0.1:
        digits = '9' * r.randint(1, 38)
    elif kind < 0.2:
        digits = '1' + '0' * r.randint(0, 37)
    else:
        digits = str(r.randint(1, 10 ** r.randint(1, 38) - 1))
    frac = r.randint(0, min(len(digits) + 3, 40))
    if frac >= len(digits):
        digits = '0' * (frac - len(digits) + 1) + digits
    text = digits[:len(digits) - frac] + ('.' + digits[len(digits) - frac:] if frac else '')
    if r.random() < 0.4:
        text = '-' + text
    return text


def sig_digits(v):
    if v == 0:
        return 0
    t = v.normalize(ctx).as_tuple()
    return len(t.digits)


def fits(v):
    if v == 0:
        return True
    t = v.normalize(ctx).as_tuple()
    n = len(t.digits)
    return n <= 38 and t.exponent >= -32768 and t.exponent + n <= 32767 + 38


def scale_of(text):
    return len(text.split('.')[1]) if '.' in text else 0


def display(v, ds):
    """obx's toStr: ds fraction digits if exact, else the canonical text."""
    q = v.quantize(D(1).scaleb(-ds, ctx), context=ctx)
    if q != v:
        return canonical(v)
    s = format(q, 'f')
    if s.startswith('-') and q == 0:
        s = s[1:]
    return s


def canonical(v):
    if v == 0:
        return '0'
    s = format(v.normalize(ctx), 'f')
    if '.' in s:
        s = s.rstrip('0').rstrip('.')
    return s


def int_digits(v):
    if v == 0:
        return 0
    t = v.normalize(ctx).as_tuple()
    return max(0, len(t.digits) + t.exponent)


def main():
    r = random.Random(20261102)
    cases = []
    for _ in range(150):
        a, b = rnd_dec(r), rnd_dec(r)
        da, db = D(a), D(b)
        sa, sb = scale_of(a), scale_of(b)
        for op in ('add', 'sub', 'mul'):
            if op == 'add':
                v, ds = ctx.add(da, db), max(sa, sb)
            elif op == 'sub':
                v, ds = ctx.subtract(da, db), max(sa, sb)
            else:
                v = ctx.multiply(da, db)
                ds = min(sa + sb, max(0, 38 - int_digits(v)))
            want = display(v, ds) if fits(v) else 'e3'
            cases.append((op, a, b, 0, 'HALF_EVEN', want))
        mode = r.choice(list(MODES))
        scale = r.randint(0, 40)
        if db != 0:
            exact = ctx.divide(da, db)
            want = rounded(exact, scale, mode, True)
            cases.append(('div', a, b, scale, mode, want))
            if r.random() < 0.5:
                rem = ctx.remainder(da, db)
                cases.append(('rem', a, b, 0, 'HALF_EVEN', display(rem, max(sa, sb))))
        cases.append(('quantize', a, '0', scale, mode, rounded(da, scale, mode)))
    # ties for every mode
    for _ in range(40):
        k = r.randint(1, 30)
        coef = r.randint(1, 10 ** r.randint(1, 30)) * 10 + 5
        text = str(coef)
        a = text[:-k] + '.' + text[-k:] if k < len(text) else '0.' + '0' * (k - len(text)) + text
        if r.random() < 0.5:
            a = '-' + a
        for mode in MODES:
            cases.append(('quantize', a, '0', k - 1, mode, rounded(D(a), k - 1, mode)))
    write(cases)


def rounded(v, scale, mode, div=False):
    """quantize (div=False) or div at scale, with obo's error order: the
    coefficient at the scale must fit 38 digits (div: the quotient may be
    10^38, which is 1e38 with one digit less), then UNNECESSARY must be exact."""
    scaled = v.scaleb(scale, ctx)
    trunc = scaled.to_integral_value(rounding=decimal.ROUND_DOWN, context=ctx)
    limit = 10 ** 38 if div else 10 ** 38 - 1
    if abs(trunc) > limit:
        return 'e1'
    if MODES[mode] is None:
        if trunc != scaled:
            return 'e3'
        res = trunc
    else:
        res = scaled.to_integral_value(rounding=MODES[mode], context=ctx)
    if abs(res) > limit:
        return 'e1'
    return display(res.scaleb(-scale, ctx), scale)


def write(cases):
    out = ['// Generated by ../gen_decimal_random.py: random add, sub, mul, div, rem and',
           '// quantize cases with results from Python\'s exact decimal module.',
           '// expect: %d cases ok' % len(cases), '',
           'var bad: int = 0', '',
           'fn d(s: str): Decimal { return Decimal.parse(s).unwrap() }', '',
           'fn txt(r: Result[Decimal, DecError]): str {',
           '    match r {',
           '        Ok(v) { return v.toStr() }',
           '        Err(e) { return "e" + e.code().toStr() }',
           '    }',
           '}', '',
           'fn chk(what: str, got: str, want: str) {',
           '    if got != want {',
           '        println("FAIL " + what + ": got " + got + ", want " + want)',
           '        bad += 1',
           '    }',
           '}', '',
           'fn main() {']
    for op, a, b, scale, mode, want in cases:
        if op == 'add':
            e = f'txt(d("{a}").addExact(d("{b}")))'
        elif op == 'sub':
            e = f'txt(d("{a}").addExact(-d("{b}")))'
        elif op == 'mul':
            e = f'txt(d("{a}").mulExact(d("{b}")))'
        elif op == 'rem':
            e = f'(d("{a}") % d("{b}")).toStr()'
        elif op == 'div':
            e = f'txt(d("{a}").div(d("{b}"), {scale}, Rounding.{mode}))'
        else:
            e = f'txt(d("{a}").quantize({scale}, Rounding.{mode}))'
        out.append(f'    chk("{op} {a} {b} {scale} {mode}", {e}, "{want}")')
    out.append(f'    println(({len(cases)} - bad).toStr() + " cases ok")')
    out.append('}')
    with open(os.path.join(HERE, 'run', 'decimal_random.obx'), 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
