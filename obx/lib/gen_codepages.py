#!/usr/bin/env python3
"""Generates codepage_data.obx, the tables of the codepage module, from
Python's codecs (the code pages' published mappings):

    python3 -I obx/lib/gen_codepages.py

Add a single-byte code page by adding one line to PAGES: (number, Python codec).
Bytes a codec leaves undefined (cp1252 has five) map to the C1 control of the
same value, as Windows and SQL Server do (see OVERRIDE).
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))

PAGES = [
    (1252, 'cp1252'),
    (28591, 'iso8859-1'),      # Latin-1; Sybase's iso_1
]


def table(codec):
    out = []
    for b in range(256):
        try:
            out.append(ord(bytes([b]).decode(codec)))
        except UnicodeDecodeError:
            out.append(b)      # undefined: the C1 control (U+0081, U+008D, ...)
    return out


def main():
    o = ['''// codepage_data: single-byte code page tables (generated; do not edit).
//
// Generated by obx/lib/gen_codepages.py from Python's codecs. For each code
// page N: DECODE_N[b] is the code point of byte b; ENC_RUNE_N holds the code
// points of the bytes 0x80 to 0xFF in ascending order and ENC_BYTE_N their
// bytes. Bytes the code page leaves undefined map to the C1 control of the
// same value.
''']
    for n, codec in PAGES:
        t = table(codec)
        assert t[:128] == list(range(128))
        pairs = sorted((t[b], b) for b in range(128, 256))
        assert len({p[0] for p in pairs}) == 128
        o.append('pub const DECODE_%d: []int = [%s]\n' % (n, ', '.join(map(str, t))))
        o.append('pub const ENC_RUNE_%d: []int = [%s]\n' % (n, ', '.join(str(p[0]) for p in pairs)))
        o.append('pub const ENC_BYTE_%d: []int = [%s]\n' % (n, ', '.join(str(p[1]) for p in pairs)))
    with open(os.path.join(HERE, 'codepage_data.obx'), 'w') as f:
        f.write('\n'.join(o))


main()
