#!/usr/bin/env python3
"""Generates the data modules of the markdown library:

  markdown_entities.obx  the HTML5 named character references, from the WHATWG
                         entities.json (https://html.spec.whatwg.org/entities.json)
  markdown_unicode.obx   Unicode punctuation and symbol ranges, Unicode white
                         space, and full case folding (for link labels), from
                         Python's unicodedata (Unicode 15.0.0 for Python 3.12)

    python3 -I obx/lib/gen_markdown_data.py --entities PATH/entities.json

entities.json is downloaded data: this script only reads it as JSON. Only the
entries whose name ends in ';' are kept (CommonMark requires the semicolon).
"""
import argparse, json, os, sys, unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))


def entities(path):
    with open(path, encoding='utf-8') as f:
        d = json.load(f)
    rows = []
    for k, v in d.items():
        if not k.startswith('&') or not k.endswith(';'):
            continue
        name = k[1:-1]
        cps = [ord(c) for c in v['characters']]
        assert 1 <= len(cps) <= 2 and name.isalnum() and name.isascii(), k
        rows.append((name, cps))
    rows.sort(key=lambda r: r[0].encode())
    out = []
    out.append('''// markdown_entities: the HTML5 named character references (generated; do not edit).
//
// Generated by obx/lib/gen_markdown_data.py from the WHATWG entities.json
// (https://html.spec.whatwg.org/entities.json, the HTML Living Standard; the
// WHATWG's data is public domain / CC0). Only the references that end in ';'
// are kept, as CommonMark requires: NAMES holds them without '&' and ';',
// sorted bytewise, and CP1[i], CP2[i] are the one or two code points of
// NAMES[i] (CP2 is 0 when there is one).

pub const COUNT = %d
''' % len(rows))
    out.append('pub const NAMES: []str = [' + ', '.join('"%s"' % r[0] for r in rows) + ']\n')
    out.append('pub const CP1: []int = [' + ', '.join(str(r[1][0]) for r in rows) + ']\n')
    out.append('pub const CP2: []int = [' + ', '.join(str(r[1][1] if len(r[1]) > 1 else 0) for r in rows) + ']\n')
    with open(os.path.join(HERE, 'markdown_entities.obx'), 'w') as f:
        f.write('\n'.join(out))


def ranges(pred):
    rs = []
    lo = None
    for c in range(0x80, 0x110000):
        if pred(c):
            if lo is None:
                lo = c
            hi = c
        elif lo is not None:
            rs.append((lo, hi))
            lo = None
    if lo is not None:
        rs.append((lo, hi))
    return rs


def unicode_tables():
    cat = lambda c: unicodedata.category(chr(c))
    punct = ranges(lambda c: cat(c)[0] in 'PS')
    space = ranges(lambda c: cat(c) == 'Zs')
    frm, start, data = [], [], []
    for c in range(0x80, 0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        s = chr(c)
        f = s.casefold()
        if f != s:
            frm.append(c)
            start.append(len(data))
            data.extend(ord(x) for x in f)
    start.append(len(data))
    out = ['''// markdown_unicode: Unicode data for the markdown library (generated; do not edit).
//
// Generated by obx/lib/gen_markdown_data.py from Python's unicodedata (Unicode
// %s): the data is Unicode's (Unicode License v3). PUNCT holds (lo, hi) pairs
// of the code points above U+007F in the general categories P and S (what
// CommonMark calls Unicode punctuation), SPACE the pairs in Zs (Unicode white
// space, with tab, LF, FF and CR), and FOLD_FROM the code points above U+007F
// that change under full case folding (CaseFolding.txt, statuses C and F):
// FOLD_FROM[i] folds to FOLD_DATA[FOLD_START[i] .. FOLD_START[i + 1]].
''' % unicodedata.unidata_version]
    out.append('pub const UNICODE_VERSION = "%s"\n' % unicodedata.unidata_version)
    out.append('pub const PUNCT: []int = [' + ', '.join('%d, %d' % r for r in punct) + ']\n')
    out.append('pub const SPACE: []int = [' + ', '.join('%d, %d' % r for r in space) + ']\n')
    out.append('pub const FOLD_FROM: []int = [' + ', '.join(map(str, frm)) + ']\n')
    out.append('pub const FOLD_START: []int = [' + ', '.join(map(str, start)) + ']\n')
    out.append('pub const FOLD_DATA: []int = [' + ', '.join(map(str, data)) + ']\n')
    with open(os.path.join(HERE, 'markdown_unicode.obx'), 'w') as f:
        f.write('\n'.join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--entities', required=True)
    a = ap.parse_args()
    entities(a.entities)
    unicode_tables()


main()
