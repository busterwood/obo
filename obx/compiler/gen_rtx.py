#!/usr/bin/env python3
"""Builds the native runtime (native/rt.c) and writes compiler/rtx.obx: its code and data as
obx constants, its symbol table and the interface header native/obxrt.h, for the native backend
(design/native.md, "Runtime").

    python3 obx/compiler/gen_rtx.py          # after changing native/rt.c, obxrt.h or rt.ld

The runtime is compiled by gcc, freestanding (no libc), and linked by ld at fixed addresses
(native/rt.ld) with libgcc for the 128-bit helpers. rtx.obx is checked in, so building the
compiler needs only gcc on the seed; the bytes depend on the gcc version that ran this.
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
NAT = os.path.join(HERE, 'native')
OUT = os.path.join(HERE, 'rtx.obx')
# -falign-functions=64: without it a change elsewhere in rt.c moved the allocator and cost
# bench alloc 26% of its cycles with the same instructions (2026-11-03).
CFLAGS = ['-O2', '-falign-functions=64', '-std=gnu11', '-ffreestanding', '-fno-builtin', '-nostdlib', '-fno-pic', '-fno-pie',
          '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-fno-tree-loop-distribute-patterns',
          '-fcf-protection=none', '-Wall', '-Wno-builtin-declaration-mismatch', '-Werror']


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"gen_rtx.py: {' '.join(cmd)} failed:\n{r.stdout}{r.stderr}")
    return r.stdout


def lit(b):
    out = []
    for x in b:
        c = chr(x)
        if c == '"' or c == '\\':
            out.append('\\' + c)
        elif 32 <= x < 127:
            out.append(c)
        else:
            out.append('\\x%02x' % x)
    return '"' + ''.join(out) + '"'


def strlit(s):
    for ch in s:
        if not (32 <= ord(ch) < 127):
            sys.exit(f"gen_rtx.py: obxrt.h has a byte obx cannot write in a literal: {ord(ch)}")
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def chunks(b, n=48):
    return [b[i:i + n] for i in range(0, len(b), n)]


def main():
    with tempfile.TemporaryDirectory() as t:
        obj = os.path.join(t, 'rt.o')
        elf = os.path.join(t, 'rt.elf')
        run(['gcc'] + CFLAGS + ['-I', NAT, '-c', os.path.join(NAT, 'rt.c'), '-o', obj])
        libgcc = run(['gcc', '-print-libgcc-file-name']).strip()
        run(['ld', '-T', os.path.join(NAT, 'rt.ld'), '-o', elf, obj, libgcc])
        for sec, name in (('.text', 'text'), ('.data', 'data')):
            run(['objcopy', '-O', 'binary', '-j', sec, '--set-section-flags', sec + '=alloc,load,contents',
                 elf, os.path.join(t, name)])
        text = open(os.path.join(t, 'text'), 'rb').read()
        data = open(os.path.join(t, 'data'), 'rb').read()
        secs = {}
        for line in run(['readelf', '-SW', elf]).splitlines():
            p = line.replace('[ ', '[').split()
            if len(p) > 5 and p[0].startswith('[') and p[1] in ('.text', '.data', '.bss'):
                secs[p[1]] = (int(p[3], 16), int(p[5], 16))
        syms = []
        for line in run(['nm', '--defined-only', elf]).splitlines():
            a, k, n = line.split()
            if k in 'TDBR':
                syms.append((n, int(a, 16)))
        syms.sort()
    taddr, tsize = secs['.text']
    daddr, dsize = secs.get('.data', (0x40000000, 0))
    baddr, bsize = secs.get('.bss', (daddr + dsize, 0))
    assert tsize == len(text) and dsize == len(data), (tsize, len(text), dsize, len(data))
    header = open(os.path.join(NAT, 'obxrt.h')).read().split('\n')
    o = ["// Generated by gen_rtx.py from native/rt.c, obxrt.h and rt.ld: do not edit.",
         "// The native runtime: its code and data (bytes), where they are linked, its global",
         "// symbols, and the C interface the backend parses before a program (design/native.md).",
         "",
         f"pub const TEXT_ADDR = {taddr}",
         f"pub const TEXT_SIZE = {len(text)}",
         f"pub const DATA_ADDR = {daddr}",
         f"pub const DATA_SIZE = {len(data)}",
         f"pub const BSS_ADDR = {baddr}",
         f"pub const BSS_SIZE = {bsize}",
         "", "pub const TEXT: []str = ["]
    o += [f"    {lit(c)}," for c in chunks(text)]
    o += ["]", "", "pub const DATA: []str = ["]
    o += [f"    {lit(c)}," for c in chunks(data)]
    o += ["]", "", "pub const SYM_NAMES: []str = ["]
    o += [f"    {strlit(n)}," for n, a in syms]
    o += ["]", "", "pub const SYM_ADDRS: []int = ["]
    o += [f"    {a}," for n, a in syms]
    o += ["]", "", "pub const HEADER: []str = ["]
    o += [f"    {strlit(x)}," for x in header]
    o += ["]", ""]
    text_out = '\n'.join(o)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text_out != old:
        with open(OUT, 'w') as f:
            f.write(text_out)
    print(f"rtx.obx: runtime text {len(text)} bytes, data {len(data)}, bss {bsize}, {len(syms)} symbols")


if __name__ == '__main__':
    main()
