#!/usr/bin/env python3
"""Writes compiler/rt.obx: ref/rt.h (the C runtime) as an obx constant, one str per line.

    python3 compiler/gen_rt.py          # run_compare.py's build runs it before compiling
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'ref', 'rt.h')
OUT = os.path.join(HERE, 'rt.obx')


def lit(s):
    for ch in s:
        if not (32 <= ord(ch) < 127):
            sys.exit(f"gen_rt.py: rt.h has a byte obx cannot write in a literal: {ord(ch)}")
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    with open(SRC) as f:
        lines = f.read().split('\n')
    out = ["// Generated by gen_rt.py from ref/rt.h: do not edit.",
           "// The C runtime, line by line (joined with newlines it is rt.h byte for byte).",
           "", "pub const RT: []str = ["]
    out += [f"    {lit(x)}," for x in lines]
    out += ["]", ""]
    text = '\n'.join(out)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text != old:
        with open(OUT, 'w') as f:
            f.write(text)


if __name__ == '__main__':
    main()
