#!/usr/bin/env python3
"""Writes compiler/obxmath.inc: the libm of obx programs, one C text shared by the C backend
(rt.h includes it, gen_rt.py pastes it in) and the native runtime (native/rt.c).

    python3 obx/compiler/gen_obxmath.py MUSL_DIR     # MUSL_DIR: an unpacked musl-1.2.5

The text is musl 1.2.5's src/math files (MIT; the exp, exp2, log, log2 and pow of Arm's
optimized-routines as musl took them in 2018; the rest from FreeBSD msun and the Sun
Microsystems notices) joined into one translation unit, with each file's own copyright
notice kept as it is. Nothing is rewritten but the #include lines, the polynomials of exp, exp2, log, log2, pow, __sin and __cos (PATCHES: fma), a `static` before the
definitions, a prefix on the global names (obx_sin ...), and `__builtin_fma` (obx_fma:
vfmadd213sd). Names that two files both define as static are renamed per file.
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'obxmath.inc')
OUTP = os.path.join(HERE, 'obxprim.inc')

# the files in dependency order
FILES = [
    'exp_data.h', 'exp_data.c', 'log_data.h', 'log_data.c', 'log2_data.h', 'log2_data.c', 'pow_data.h', 'pow_data.c',
    '__math_xflow.c', '__math_oflow.c', '__math_uflow.c', '__math_divzero.c', '__math_invalid.c',
    'scalbn.c', 'expm1.c', 'log1p.c',
    '__rem_pio2_large.c', '__rem_pio2.c', '__sin.c', '__cos.c', '__tan.c', 'sin.c', 'cos.c', 'tan.c',
    'atan.c', 'atan2.c', 'asin.c', 'acos.c',
    'exp.c', 'exp2.c', 'log.c', 'log2.c', 'pow.c', '__expo2.c',
    'sinh.c', 'cosh.c', 'tanh.c', 'log10.c', 'cbrt.c', 'hypot.c', 'fmod.c',
]
PUBLIC = ['exp', 'exp2', 'log', 'log2', 'pow', 'sin', 'cos', 'tan', 'asin', 'acos', 'atan', 'atan2', 'sinh', 'cosh', 'tanh',
          'log10', 'log1p', 'expm1', 'cbrt', 'hypot', 'scalbn', 'fmod']
INTERNAL = ['__sin', '__cos', '__tan', '__rem_pio2', '__rem_pio2_large', '__expo2', '__math_oflow', '__math_uflow',
            '__math_xflow', '__math_divzero', '__math_invalid', '__exp_data', '__log_data', '__log2_data', '__pow_log_data']
# provided by the prelude (instructions)
PRELUDE_FNS = ['sqrt', 'fabs', 'floor', 'copysign']

PRIMS = r'''/* obxprim.inc: the libm functions that are single instructions (generated by gen_obxmath.py;
   do not edit). In rt.h and native/rt.c; obxmath.inc uses them. Needs AVX and FMA3 (VEX forms: no false dependency on the destination). */
#include <stdint.h>
#define OBXP static __attribute__((unused))
/* the instructions */
OBXP inline double obx_sqrt(double x) { double r; __asm__("vsqrtsd %1, %1, %0" : "=x"(r) : "x"(x)); return r; }
OBXP inline double obx_floor(double x) { double r; __asm__("vroundsd $9, %1, %1, %0" : "=x"(r) : "x"(x)); return r; }
OBXP inline double obx_ceil(double x) { double r; __asm__("vroundsd $10, %1, %1, %0" : "=x"(r) : "x"(x)); return r; }
OBXP inline double obx_trunc(double x) { double r; __asm__("vroundsd $11, %1, %1, %0" : "=x"(r) : "x"(x)); return r; }
OBXP inline double obx_rint(double x) { double r; __asm__("vroundsd $12, %1, %1, %0" : "=x"(r) : "x"(x)); return r; }
OBXP inline double obx_fma(double a, double b, double c) { __asm__("vfmadd213sd %2, %1, %0" : "+x"(a) : "x"(b), "x"(c)); return a; }
OBXP inline double obx_fabs(double x) { union { double d; uint64_t u; } v; v.d = x; v.u &= ~(1ULL << 63); return v.d; }
OBXP inline double obx_copysign(double x, double y) {
    union { double d; uint64_t u; } a, b;
    a.d = x; b.d = y;
    a.u = (a.u & ~(1ULL << 63)) | (b.u & (1ULL << 63));
    return a.d;
}
/* half away from zero: trunc(x + copysign(0.49999999999999994, x)) */
OBXP inline double obx_round(double x) { return obx_trunc(x + obx_copysign(0.49999999999999994, x)); }
'''

PRELUDE = r'''/* obxmath.inc: the libm of obx programs (generated by gen_obxmath.py; do not edit).
   The C backend (rt.h) and the native runtime (native/rt.c) compile this same text, so that
   both give the same bits. Sources, all permissive and unchanged but for the mechanical
   renaming above each file's notice:
     musl 1.2.5 (https://git.musl-libc.org/cgit/musl/tag/?h=v1.2.5), src/math: MIT,
       Copyright (c) 2005-2020 Rich Felker, et al.; the files keep their own notices (Arm Limited
       for exp, exp2, log, log2, pow: Arm optimized-routines as musl imported them; Sun
       Microsystems and FreeBSD msun for the rest).
   Requires SSE4.1 (roundsd) and FMA3 (vfmadd213sd), as every obx program does. No FMA is
   contracted by the compiler: the only fma is obx_fma. obxprim.inc comes first. */
#include <stdint.h>
#include <float.h>
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wparentheses"
#pragma GCC diagnostic ignored "-Wunused-but-set-variable"
#pragma GCC diagnostic ignored "-Wunused-function"
#pragma GCC diagnostic ignored "-Wmaybe-uninitialized"
#define OBXM static __attribute__((unused))
#define hidden
#define double_t double
#define float_t float
#undef isnan
#undef isinf
#undef isfinite
#define isnan(x) __builtin_isnan(x)
#define isinf(x) __builtin_isinf(x)
#define isfinite(x) __builtin_isfinite(x)
#define weak_alias(a, b)
#undef INFINITY
#undef NAN
#define INFINITY __builtin_inf()
#define NAN __builtin_nan("")
#define predict_true(x) __builtin_expect(!!(x), 1)
#define predict_false(x) __builtin_expect(x, 0)
#define WANT_ROUNDING 1
#define __FP_FAST_FMA 1
#define __builtin_fma obx_fma
#define TOINT_INTRINSICS 0

#define sqrt obx_sqrt
#define fabs obx_fabs
#define floor obx_floor
#define copysign obx_copysign
'''

LIBM_H = r'''
#define asuint(f) ((union{float _f; uint32_t _i;}){f})._i
#define asfloat(i) ((union{uint32_t _i; float _f;}){i})._f
#define asuint64(f) ((union{double _f; uint64_t _i;}){f})._i
#define asdouble(i) ((union{uint64_t _i; double _f;}){i})._f
#define issignalingf_inline(x) 0
#define issignaling_inline(x) 0
static inline float eval_as_float(float x) { float y = x; return y; }
static inline double eval_as_double(double x) { double y = x; return y; }
static inline double fp_barrier(double x) { volatile double y = x; return y; }
static inline void fp_force_eval(double x) { volatile double y; y = x; }
static inline void fp_force_evalf(float x) { volatile float y; y = x; }
#define FORCE_EVAL(x) do { if (sizeof(x) == sizeof(float)) { fp_force_evalf(x); } else { fp_force_eval(x); } } while(0)
#define EXTRACT_WORDS(hi,lo,d) do { uint64_t __u = asuint64(d); (hi) = __u >> 32; (lo) = (uint32_t)__u; } while (0)
#define GET_HIGH_WORD(hi,d) do { (hi) = asuint64(d) >> 32; } while (0)
#define GET_LOW_WORD(lo,d) do { (lo) = (uint32_t)asuint64(d); } while (0)
#define INSERT_WORDS(d,hi,lo) do { (d) = asdouble(((uint64_t)(hi)<<32) | (uint32_t)(lo)); } while (0)
#define SET_HIGH_WORD(d,hi) INSERT_WORDS(d, hi, (uint32_t)asuint64(d))
#define SET_LOW_WORD(d,lo) INSERT_WORDS(d, asuint64(d)>>32, lo)
'''



# The polynomials of the hot functions, evaluated with fma (FMA3 is required anyway): shorter
# dependency chains and slightly smaller errors. Each entry is (file, upstream text, replacement);
# the text must occur exactly once.
F = '__builtin_fma'
PATCHES = [
    ('exp.c', 'r = x + kd * NegLn2hiN + kd * NegLn2loN;', 'r = %s(kd, NegLn2loN, %s(kd, NegLn2hiN, x));' % (F, F)),
    ('exp.c', 'tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);',
     'tmp = %s(r2 * r2, %s(r, C5, C4), %s(r2, %s(r, C3, C2), tail + r));' % (F, F, F, F)),
    ('exp.c', 'return eval_as_double(scale + scale * tmp);', 'return %s(scale, tmp, scale);' % F),
    ('pow.c', 'r = x + kd * NegLn2hiN + kd * NegLn2loN;', 'r = %s(kd, NegLn2loN, %s(kd, NegLn2hiN, x));' % (F, F)),
    ('pow.c', 'tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);',
     'tmp = %s(r2 * r2, %s(r, C5, C4), %s(r2, %s(r, C3, C2), tail + r));' % (F, F, F, F)),
    ('pow.c', 'return eval_as_double(scale + scale * tmp);', 'return %s(scale, tmp, scale);' % F),
    ('pow.c', 'p = (ar3 * (A[1] + r * A[2] +\n\t\t    ar2 * (A[3] + r * A[4] + ar2 * (A[5] + r * A[6]))));',
     'p = ar3 * %s(ar2, %s(ar2, %s(r, A[6], A[5]), %s(r, A[4], A[3])), %s(r, A[2], A[1]));' % (F, F, F, F, F)),
    ('exp2.c', 'tmp = tail + r * C1 + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);',
     'tmp = %s(r2 * r2, %s(r, C5, C4), %s(r2, %s(r, C3, C2), %s(r, C1, tail)));' % (F, F, F, F, F)),
    ('exp2.c', 'return eval_as_double(scale + scale * tmp);', 'return %s(scale, tmp, scale);' % F),
    ('log.c', 'y = lo + r2 * A[0] +\n\t    r * r2 * (A[1] + r * A[2] + r2 * (A[3] + r * A[4])) + hi;',
     'y = %s(r * r2, %s(r2, %s(r, A[4], A[3]), %s(r, A[2], A[1])), %s(r2, A[0], lo)) + hi;' % (F, F, F, F, F)),
    ('log2.c', 'p = A[0] + r * A[1] + r2 * (A[2] + r * A[3]) + r4 * (A[4] + r * A[5]);',
     'p = %s(r4, %s(r, A[5], A[4]), %s(r2, %s(r, A[3], A[2]), %s(r, A[1], A[0])));' % (F, F, F, F, F)),
    ('__sin.c', 'r = S2 + z*(S3 + z*S4) + z*w*(S5 + z*S6);',
     'r = %s(z * w, %s(z, S6, S5), %s(z, %s(z, S4, S3), S2));' % (F, F, F, F)),
    ('__sin.c', 'return x + v*(S1 + z*r);', 'return %s(v, %s(z, r, S1), x);' % (F, F)),
    ('__cos.c', 'r  = z*(C1+z*(C2+z*C3)) + w*w*(C4+z*(C5+z*C6));',
     'r  = %s(w * w, %s(z, %s(z, C6, C5), C4), z * %s(z, %s(z, C3, C2), C1));' % (F, F, F, F, F)),
]


def renames():
    m = {}
    for n in PUBLIC + INTERNAL:
        m[n] = 'obx_' + n
    return m


def file_text(musl, name):
    p = os.path.join(musl, 'src', 'math', name)
    t = open(p).read()
    t = re.sub(r'^\s*#\s*include\s+.*\n', '', t, flags=re.M)
    for pf, old, new in PATCHES:
        if pf == name:
            assert t.count(old) == 1, (pf, old)
            t = t.replace(old, new)
    t = t.replace('#ifndef _EXP_DATA_H\n#define _EXP_DATA_H\n', '')
    for g in ('LOG_DATA', 'LOG2_DATA', 'POW_DATA'):
        t = t.replace('#ifndef _%s_H\n#define _%s_H\n' % (g, g), '')
    if name.endswith('_data.h'):
        t = re.sub(r'#endif\s*$', '', t.rstrip()) + '\n'
        t = t.replace('extern hidden const struct', 'OBXM const struct')
    else:
        # a definition of a global at the start of a line gets OBXM
        t = re.sub(r'^(const struct \w+ __\w+ =)', r'OBXM \1', t, flags=re.M)
        t = re.sub(r'^(?!static|OBXM)((?:double|int|float|void)\s+\**)(\w+)\(', r'OBXM \1\2(', t, flags=re.M)
    return t


def defines_of(t):
    return sorted(set(re.findall(r'^\s*#\s*define\s+(\w+)', t, flags=re.M)))


def build(musl, clash):
    out = [PRELUDE, LIBM_H]
    rn = renames()
    out.append('/* the global names */')
    for k, v in rn.items():
        out.append('#define %s %s' % (k, v))
    out.append('')
    for f in FILES:
        t = file_text(musl, f)
        tag = re.sub(r'\W', '_', f.rsplit('.', 1)[0]).strip('_')
        d = defines_of(t)
        sec = ['/* ---- musl 1.2.5 src/math/%s ---- */' % f]
        mine = [n for n in sorted(clash) if re.search(r'\b%s\b' % re.escape(n), t) and n not in d]
        for n in mine:
            sec.append('#define %s %s__%s' % (n, n, tag))
        sec.append(t.rstrip('\n'))
        for n in ([] if f.endswith('.h') else d) + mine:
            sec.append('#undef ' + n)
        out.append('\n'.join(sec))
        out.append('')
    out.append('/* ---- end: the macros of this file go away */')
    for k in list(rn) + PRELUDE_FNS + ['OBXM', 'hidden', 'double_t', 'float_t', 'isnan', 'isinf', 'isfinite', 'weak_alias',
                                       'predict_true', 'predict_false', 'WANT_ROUNDING', '__FP_FAST_FMA', '__builtin_fma',
                                       'TOINT_INTRINSICS', 'INFINITY', 'NAN', 'asuint', 'asfloat', 'asuint64', 'asdouble', 'issignalingf_inline',
                                       'issignaling_inline', 'FORCE_EVAL', 'EXTRACT_WORDS', 'GET_HIGH_WORD', 'GET_LOW_WORD',
                                       'INSERT_WORDS', 'SET_HIGH_WORD', 'SET_LOW_WORD']:
        out.append('#undef ' + k)
    out.append('#pragma GCC diagnostic pop')
    txt = '\n'.join(out) + '\n'
    return txt.expandtabs(8).replace('\u00a9', '(c)').encode('ascii', 'replace').decode()


def try_compile(src):
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, 't.c')
        open(c, 'w').write('#include <stdint.h>\n' + PRIMS + src + '\nint main(void) { return 0; }\n')
        r = subprocess.run(['gcc', '-fsyntax-only', '-Wall', '-Wextra', '-Wno-unused-parameter', '-std=gnu11', c], capture_output=True, text=True)
        return r.stderr


def main():
    musl = sys.argv[1]
    clash = set()
    for _ in range(12):
        src = build(musl, clash)
        err = try_compile(src)
        new = set(re.findall(r"redefinition of [‘'](\w+)[’']", err)) | set(re.findall(r"conflicting types for [‘'](\w+)[’']", err))
        new |= set(re.findall(r"[‘'](\w+)[’'] redeclared", err))
        new -= clash
        if not new:
            break
        clash |= new
    if err.strip():
        sys.stderr.write(err[:6000])
        sys.exit('gen_obxmath.py: the text does not compile cleanly')
    open(OUT, 'w').write(src)
    open(OUTP, 'w').write(PRIMS)
    rt = os.path.join(HERE, 'rt.h')
    t = open(rt).read()
    i = t.index('/* BEGIN obxprim.inc')
    j = t.index('/* END obxprim.inc */')
    body = PRIMS.replace('#include <stdint.h>\n', '')
    t = t[:i] + '/* BEGIN obxprim.inc (gen_obxmath.py) */\n' + body + t[j:]
    open(rt, 'w').write(t)
    print('obxmath.inc: %d bytes, %d files; renamed per file: %s' % (len(src), len(FILES), ' '.join(sorted(clash))))


main()
