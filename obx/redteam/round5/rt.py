#!/usr/bin/env python3
"""Red-team runner, round 5: compile each case with --emit-c, build with ASan+UBSan, run with
OBX_CHECK=1, compare to directives (// expect:, // exit:, // error:); then build the same case
with --native and run it (with OBX_CHECK=1) and compare it to the C build (stdout, exit code).
Classify:
  OK        matches the directives (and the native build agrees, or refuses cleanly)
  ASAN      sanitizer report (memory error / UB)
  LEAK      exit 5 under OBX_CHECK (or LeakSanitizer)
  CRASH     compiler crash (exit status other than 0 and 1, or a traceback)
  CCFAIL    generated C failed to compile
  REJECT    compile error but a run was expected
  ACCEPT    compiled but an error was expected
  MISMATCH  output/exit differs
  NATIVE    the native build differs from the directives (or failed to build)
A case marked `// expect-any` (generated by gen.py) takes the C build's output as its expectation:
its oracle is a clean sanitizer run with OBX_CHECK=1 and the native build printing the same.
usage: rt.py [--probe] [--no-native] [files or dirs...]   (default: cases/ and gen/)
"""
import os, re, json, subprocess, sys, glob, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tools'))
import cbuild
from concurrent.futures import ThreadPoolExecutor
HERE = os.path.dirname(os.path.abspath(__file__))
OBXC = cbuild.OBXC   # $OBXC, else compiler/out/obxc
BUILD = os.path.join(HERE, 'build' + ('_' + os.path.basename(os.environ['CC']) if os.environ.get('CC') else ''))
DIRECTIVE = re.compile(r'^\s*//\s*(expect|exit|error|stdin):(.*)$')
ANY = re.compile(r'^\s*//\s*expect-any\s*$')
os.environ.setdefault('OBX_LIB', os.path.normpath(os.path.join(HERE, '..', '..', 'lib')))

def directives(path):
    d = {'expect': [], 'exit': 0, 'error': None, 'any': False}
    for raw in open(path, encoding='utf-8', errors='replace', newline=''):
        if ANY.match(raw): d['any'] = True
        m = DIRECTIVE.match(raw.rstrip('\r\n'))
        if not m: continue
        k, v = m.group(1), m.group(2)
        if v.startswith(' '): v = v[1:]
        if k == 'expect': d['expect'].append(v)
        elif k == 'exit': d['exit'] = int(v.strip())
        elif k == 'error': d['error'] = (d['error'] or []) + [v.strip()]
    return d

def lines(s):
    out = s.split('\n')
    if out and out[-1] == '': out.pop()
    return out

def native(path, d):
    with tempfile.TemporaryDirectory(prefix='rt5n_') as tmp:
        exe = os.path.join(tmp, 'n.out')
        try:
            c = subprocess.run(cbuild.obxc_argv(OBXC) + [path, '--native', '-o', exe], capture_output=True, text=True, timeout=60)
        except subprocess.TimeoutExpired:
            return 'native build timeout'
        if c.returncode != 0:
            msg = (c.stdout + c.stderr).strip()
            if 'native: unsupported:' in msg and c.returncode == 1: return None
            return 'native build failed (%d): %s' % (c.returncode, msg[:300])
        env = dict(os.environ, OBX_CHECK='1')
        try:
            r = subprocess.run([exe], capture_output=True, text=True, errors='replace', timeout=20, env=env, cwd=tmp)
        except subprocess.TimeoutExpired:
            return 'native timeout'
        out = lines(r.stdout)
        if out != d['expect'] or r.returncode != d['exit']:
            return f"native exit {r.returncode} (want {d['exit']}) out={out[:8]} want={d['expect'][:8]} err={r.stderr.strip()[:150]}"
    return None

def run1(path):
    name = os.path.splitext(os.path.basename(path))[0]
    d = directives(path)
    if name == 'main':
        name = os.path.basename(os.path.dirname(path))
    try:
        c = subprocess.run(cbuild.obxc_argv(OBXC) + [path, '--emit-c-json'], capture_output=True, text=True, timeout=30)
    except subprocess.TimeoutExpired:
        return name, 'HANG', 'compiler did not finish in 30 s'
    if 'Traceback' in c.stderr or c.returncode not in (0, 1):
        return name, 'CRASH', f'exit {c.returncode}: ' + (c.stderr.strip().splitlines() or [''])[-1]
    if c.returncode != 0:
        msg = c.stderr.strip()
        if d['error'] is not None:
            ok = all(any(w.lower() in msg.lower() for w in e.split('|')) for e in d['error'] if e)
            return name, 'OK' if ok else 'WRONGMSG', msg
        return name, 'REJECT', msg
    if d['error'] is not None and not PROBE:
        return name, 'ACCEPT', 'compiled'
    j = json.loads(c.stdout)
    links = j['cmd'][j['cmd'].index('@SRC@') + 1:]
    cfile = os.path.join(BUILD, name + '.c'); exe = os.path.join(BUILD, name)
    open(cfile, 'w').write(j['c'])
    cc = os.environ.get('CC', 'gcc')
    san = 'address,undefined' + (',function' if 'clang' in cc else '')
    grc, gerr = cbuild.cc_build(j['c'], [cc, '-g', '-O0', '-std=gnu11', '-fsanitize=' + san,
                        '-fno-sanitize-recover=undefined', '-w', '-o', '@OUT@', '@SRC@'] + links, exe)
    if grc != 0:
        return name, 'CCFAIL', gerr[:600]
    env = dict(os.environ, OBX_CHECK='1', ASAN_OPTIONS='detect_leaks=1:abort_on_error=0:exitcode=99',
               UBSAN_OPTIONS='print_stacktrace=1:halt_on_error=1:exitcode=98')
    try:
        r = subprocess.run([exe], capture_output=True, text=True, errors='replace', timeout=20, env=env)
    except subprocess.TimeoutExpired:
        return name, 'TIMEOUT', ''
    err = r.stderr
    if PROBE:
        first = next((l for l in err.splitlines() if 'ERROR' in l or 'runtime error' in l or l.startswith('obx:')), '')
        return name, 'PROBE', f"exit {r.returncode} out={r.stdout.splitlines()[:6]} {first.strip()[:200]}"
    if 'AddressSanitizer' in err or 'runtime error:' in err or r.returncode in (98, 99):
        first = next((l for l in err.splitlines() if 'ERROR' in l or 'runtime error' in l), err[:200])
        return name, 'ASAN', first.strip()
    if 'LeakSanitizer' in err or r.returncode == 5 and d['exit'] != 5:
        return name, 'LEAK', err.strip().splitlines()[0] if err.strip() else ''
    out = lines(r.stdout)
    if d['any']: d['expect'] = out     # generated: the oracle is a clean run, and native agreeing
    if out != d['expect'] or r.returncode != d['exit']:
        return name, 'MISMATCH', f"exit {r.returncode} (want {d['exit']}) out={out[:8]} want={d['expect'][:8]} err={err.strip()[:150]}"
    if NATIVE:
        why = native(path, d)
        if why: return name, 'NATIVE', why
    return name, 'OK', ''

PROBE = False
NATIVE = True

def main(args):
    global PROBE, NATIVE
    while args and args[0].startswith('--'):
        if args[0] == '--probe': PROBE = True
        elif args[0] == '--no-native': NATIVE = False
        args = args[1:]
    os.makedirs(BUILD, exist_ok=True)
    files = []
    for a in args or [os.path.join(HERE, 'cases'), os.path.join(HERE, 'gen')]:
        if os.path.isdir(a) and os.path.exists(os.path.join(a, 'main.obx')): files.append(os.path.join(a, 'main.obx'))
        elif os.path.isdir(a):
            files += sorted(glob.glob(os.path.join(a, '*.obx')))
            files += sorted(glob.glob(os.path.join(a, '*', 'main.obx')))
        elif os.path.exists(a): files.append(a)
    with ThreadPoolExecutor(8) as ex:
        res = list(ex.map(run1, files))
    for n, k, m in res:
        if k != 'OK' or '-v' in os.environ.get('RTV', ''):
            print(f"{k:9} {n}: {m[:300]}")
    from collections import Counter
    print(dict(Counter(k for _, k, _ in res)))

if __name__ == '__main__':
    main(sys.argv[1:])
